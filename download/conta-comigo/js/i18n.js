let LANG = 'pt';
function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key] != null) ? I18N[LANG][key] : (I18N.pt[key] != null ? I18N.pt[key] : key);
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}
/* v2.4: variante para bibliotecas de frases (arrays) — escolhe aleatória e preenche */
function tpick(key, vars) {
  const arr = (I18N[LANG] && I18N[LANG][key]) || I18N.pt[key] || [key];
  let s = (typeof rand === 'function' && arr.length) ? arr[rand(0, arr.length - 1)] : arr[0];
  if (vars) for (const k in vars) s = String(s).split('{' + k + '}').join(String(vars[k]));
  return s;
}
const TTS_LANG = { pt: 'pt-BR', en: 'en-US', es: 'es-ES' };

/* Aplica o idioma aos elementos estáticos (usado por todas as páginas) */
function applyLang() {
  try { LANG = (typeof G === 'function' && G() && G().lang) ? G().lang : 'pt'; } catch (e) { LANG = 'pt'; }
  document.documentElement.lang = TTS_LANG[LANG] || 'pt-BR';
  document.title = t('appName') + ' — ' + t('subtitle');
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  applyI18nLabels(document);
}
/* Botões só com emoji ganham nome acessível traduzido: data-i18n-label="chave"
   vira aria-label (e, nos botões, também a dica do mouse) */
function applyI18nLabels(root) {
  root.querySelectorAll('[data-i18n-label]').forEach((el) => {
    const s = t(el.dataset.i18nLabel);
    el.setAttribute('aria-label', s);
    if (el.tagName === 'BUTTON') el.title = s;
  });
}

/* Números por extenso (0–59) para narração (S21/S22) */
const NUMW = {
  pt: { ones: ['zero','um','dois','três','quatro','cinco','seis','sete','oito','nove','dez','onze','doze','treze','quatorze','quinze','dezesseis','dezessete','dezoito','dezenove'], tens: ['', '', 'vinte','trinta','quarenta','cinquenta'], j: ' e ' },
  en: { ones: ['zero','one','two','three','four','five','six','seven','eight','nine','ten','eleven','twelve','thirteen','fourteen','fifteen','sixteen','seventeen','eighteen','nineteen'], tens: ['', '', 'twenty','thirty','forty','fifty'], j: '-' },
  es: { ones: ['cero','uno','dos','tres','cuatro','cinco','seis','siete','ocho','nueve','diez','once','doce','trece','catorce','quince','dieciséis','diecisiete','dieciocho','diecinueve'], tens: ['', '', 'veinte','treinta','cuarenta','cincuenta'], j: ' y ' },
};
function numWord(lang, n) {
  const d = NUMW[lang] || NUMW.pt;
  n = Math.max(0, Math.min(59, n | 0));
  if (n < 20) return d.ones[n];
  if (n === 20) return d.tens[2];
  const tI = Math.floor(n / 10), o = n % 10;
  if (lang === 'es' && tI === 2) return 'veinti' + d.ones[o];
  if (o === 0) return d.tens[tI];
  return d.tens[tI] + d.j + d.ones[o];
}
