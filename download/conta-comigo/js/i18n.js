/* Números por extenso (0–59) para narração (S21/S22) */
const NUMW = {
  pt: { ones: ['zero','um','dois','três','quatro','cinco','seis','sete','oito','nove','dez','onze','doze','treze','quatorze','quinze','dezesseis','dezessete','dezoito','dezenove'], tens: ['', '', 'vinte','trinta','quarenta','cinquenta'], j: ' e ' },
  en: { ones: ['zero','one','two','three','four','five','six','seven','eight','nine','ten','eleven','twelve','thirteen','fourteen','fifteen','sixteen','seventeen','eighteen','nineteen'], tens: ['', '', 'twenty','thirty','forty','fifty'], j: '-' },
  es: { ones: ['cero','uno','dos','tres','cuatro','cinco','seis','siete','ocho','nueve','diez','once','doce','trece','catorce','quince','dieciséis','diecisiete','dieciocho','diecinueve'], tens: ['', '', 'veinte','treinta','cuarenta','cincuenta'], j: ' y ' },
};
function numWord(lang, n) {
  const d = NUMW[lang] || NUMW.pt;
  n = Math.max(0, Math.min(59, n | 0));
  if (n < 20) return d.ones[n];
  if (n === 20) return d.tens[2];
  const tI = Math.floor(n / 10), o = n % 10;
  if (lang === 'es' && tI === 2) return 'veinti' + d.ones[o];
  if (o === 0) return d.tens[tI];
  return d.tens[tI] + d.j + d.ones[o];
}
